const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const source=fs.readFileSync('frontend/i18n-core.js','utf8');
  const {createTranslator,formatDate,formatNumber,relativeTime}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  const dictionary=JSON.parse(fs.readFileSync('frontend/locales/ru.json','utf8'));
  const missing=[];
  const {t,label,plural}=createTranslator(dictionary,{debug:true,onMissing:message=>missing.push(message)});
  for(const [count,expected] of [[0,'0 событий'],[1,'1 событие'],[2,'2 события'],[5,'5 событий'],[11,'11 событий'],[21,'21 событие'],[22,'22 события'],[25,'25 событий'],[101,'101 событие']])assert.equal(plural('counts.events',count),expected);
  assert.equal(plural('counts.honeypots',3),'3 ловушки');
  assert.equal(plural('counts.attempts',20),'20 попыток');
  assert.equal(formatNumber(12345.5),'12\u00a0345,5');
  assert.match(formatDate('2026-10-10T12:30:00Z'),/10\.10\.2026, \d{2}:30:00/);
  assert.equal(formatDate('invalid'),'—');
  const now=Date.parse('2026-10-10T12:00:00Z');
  assert.equal(relativeTime(now-60000,now),'1 минуту назад');
  assert.equal(relativeTime(now-120000,now),'2 минуты назад');
  assert.equal(relativeTime(now-300000,now),'5 минут назад');
  assert.equal(relativeTime(now-86400000,now),'вчера');
  assert.equal(relativeTime(null,now),'—');
  assert.equal(label('audit','profile.create'),'Создание профиля');
  assert.equal(label('role','viewer'),'Наблюдатель');
  assert.equal(label('interaction','medium'),'Средний уровень взаимодействия');
  assert.equal(label('severity','medium'),'Средний');
  const hostile='<img src=x onerror=alert(1)>';
  assert.equal(t('settings.editTitle',{name:hostile}),'Изменить доступ · '+hostile);
  assert.equal(t('not.present'),'Текст недоступен');
  assert.equal(missing.length,1);
  const quiet=[];createTranslator(dictionary,{onMissing:message=>quiet.push(message)}).t('not.present');assert.equal(quiet.length,0);
  console.log('УСПЕШНО: склонения ru-RU, даты, числа, относительное время, параметры и безопасный запасной текст.');
})().catch(error=>{console.error(error);process.exitCode=1;});
